def build_pc_user_agent_profile(row: tuple[str, str, str, str, int, tuple[str, ...]]) -> dict[str, object]:
    profile_id, browser, channel, ua_string, weight, tags = row
    ua_data = generate_ua_data_from_ua(ua_string)
    headers = generate_headers_from_ua(ua_string)
    base_platform = get_base_platform(ua_string)
    return {
        "id": profile_id,
        "browser": browser,
        "channel": channel,
        "weight": weight,
        "tags": tags,
        "userAgent": ua_string,
        "appVersion": _app_version_from_ua(ua_string),
        "platform": base_platform,
        "userAgentData": ua_data,
        "headers": headers,
        "navigator": {
            "userAgent": ua_string,
            "appVersion": _app_version_from_ua(ua_string),
            "platform": base_platform,
            "vendor": "Google Inc.",
            "userAgentData": ua_data,
        },
    }


def build_pc_user_agent_profile_from_ua(
    user_agent: str,
    profile_id: str = "custom_user_agent",
    browser: str | None = None,
) -> dict[str, object]:
    original_ua_string = str(user_agent or "").strip()
    ua_string = normalize_pc_user_agent_version(original_ua_string)
    if not ua_string:
        raise ValueError("user_agent is required")
    browser_name = browser or ("edge" if " Edg/" in ua_string else "chrome")
    version_options = _custom_full_version_options(original_ua_string)
    ua_data = generate_ua_data_from_ua(ua_string, version_options)
    headers = generate_headers_from_ua(ua_string, version_options)
    base_platform = get_base_platform(ua_string)
    tags = ("custom",)
    if "ARM64" in ua_string.upper():
        tags = ("custom", "arm64")
    return {
        "id": profile_id,
        "browser": browser_name,
        "channel": "custom",
        "weight": 1,
        "tags": tags,
        "userAgent": ua_string,
        "appVersion": _app_version_from_ua(ua_string),
        "platform": base_platform,
        "userAgentData": ua_data,
        "headers": headers,
        "navigator": {
            "userAgent": ua_string,
            "appVersion": _app_version_from_ua(ua_string),
            "platform": base_platform,
            "vendor": "Google Inc.",
            "userAgentData": ua_data,
        },
    }


PC_USER_AGENT_PROFILES: tuple[dict[str, object], ...] = tuple(
    build_pc_user_agent_profile(row) for row in PC_USER_AGENT_ROWS
)


def get_pc_user_agent_profiles(
    browser: str | None = None,
    tag: str | None = None,
) -> tuple[dict[str, object], ...]:
    browser_key = str(browser or "").strip().lower()
    tag_key = str(tag or "").strip().lower()
    output = []
    for profile in PC_USER_AGENT_PROFILES:
        if browser_key and str(profile.get("browser", "")).lower() != browser_key:
            continue
        if tag_key:
            tags = tuple(str(item).lower() for item in profile.get("tags", ()))
            if tag_key not in tags:
                continue
        output.append(profile)
    return tuple(output)


def choose_pc_user_agent_profile(
    rng: random.Random,
    browser: str | None = None,
    tag: str | None = None,
) -> dict[str, object]:
    profiles = get_pc_user_agent_profiles(browser=browser, tag=tag)
    if not profiles:
        profiles = PC_USER_AGENT_PROFILES
    weights = [int(profile.get("weight", 1)) for profile in profiles]
    return rng.choices(profiles, weights=weights, k=1)[0]


def build_pc_user_agent_patch(profile: dict[str, object]) -> dict[str, object]:
    return {
        "navigator": profile.get("navigator", {}),
        "userAgentData": profile.get("userAgentData", {}),
        "headers": profile.get("headers", {}),
        "userAgentProfileId": profile.get("id", ""),
        "browser": profile.get("browser", ""),
        "browserChannel": profile.get("channel", ""),
    }


def iter_pc_user_agents(browser: str | None = None) -> Iterable[str]:
    for profile in get_pc_user_agent_profiles(browser=browser):
        yield str(profile.get("userAgent", ""))
