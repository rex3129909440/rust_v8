def _app_version_from_ua(ua_string: str) -> str:
    prefix = "Mozilla/"
    return ua_string[len(prefix):] if ua_string.startswith(prefix) else ua_string


def normalize_pc_user_agent_version(ua_string: str) -> str:
    import re

    ua_string = re.sub(
        r"\bChrome/(\d+)(?:\.\d+){0,3}",
        lambda match: f"Chrome/{clamp_supported_chromium_major(match.group(1))}.0.0.0",
        str(ua_string or ""),
    )
    ua_string = re.sub(
        r"\bEdg/(\d+)(?:\.\d+){0,3}",
        lambda match: f"Edg/{clamp_supported_chromium_major(match.group(1))}.0.0.0",
        ua_string,
    )
    return ua_string


def _custom_full_version_options(original_ua_string: str) -> dict[str, str]:
    parsed = parse_ua(original_ua_string)
    options: dict[str, str] = {}
    if has_specific_full_version(parsed.get("fullChromeVersion")):
        options["chromeFullVersion"] = str(parsed["fullChromeVersion"])
    if parsed.get("isEdge") and has_specific_full_version(parsed.get("fullEdgeVersion")):
        options["edgeFullVersion"] = str(parsed["fullEdgeVersion"])
    return options


