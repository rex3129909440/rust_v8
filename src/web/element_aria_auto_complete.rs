pub(crate) fn define(
    s: &mut v8::PinScope<'_, '_>,
    p: v8::Local<'_, v8::Object>,
) -> Result<(), String> {
    crate::webidl::define_accessor(
        s,
        p,
        "ariaAutoComplete",
        get_aria_auto_complete,
        set_aria_auto_complete,
    )
}
fn get_aria_auto_complete(
    s: &mut v8::PinScope<'_, '_>,
    a: v8::FunctionCallbackArguments<'_>,
    r: v8::ReturnValue<'_>,
) {
    super::element_aria_reflection::get_string(s, a, r, "aria-autocomplete")
}
fn set_aria_auto_complete(
    s: &mut v8::PinScope<'_, '_>,
    a: v8::FunctionCallbackArguments<'_>,
    _: v8::ReturnValue<'_>,
) {
    super::element_aria_reflection::set_string(s, a, "aria-autocomplete")
}
