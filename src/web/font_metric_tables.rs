pub(crate) fn implicit_default_advance_width(text: &str, font_size: f64) -> Option<f64> {
    let mut width = 0.0;
    let mut previous = None;
    for character in text.chars() {
        if !((' '..='~').contains(&character)) {
            return None;
        }
        width += IMPLICIT_DEFAULT_ASCII_100[character as usize - 32];
        if let Some(left) = previous {
            let key = (left as u8, character as u8);
            if let Ok(index) = IMPLICIT_DEFAULT_KERNING_100
                .binary_search_by_key(&key, |(left, right, _)| (*left, *right))
            {
                width += IMPLICIT_DEFAULT_KERNING_100[index].2;
            }
        }
        previous = Some(character);
    }
    Some(width * font_size / 100.0)
}

pub(crate) fn implicit_default_line_height(font_size: f64) -> f64 {
    if !font_size.is_finite() || font_size <= 0.0 {
        return 0.0;
    }
    let integer_size = font_size.floor().max(1.0) as usize;
    if integer_size <= IMPLICIT_DEFAULT_LINE_HEIGHTS.len() {
        f64::from(IMPLICIT_DEFAULT_LINE_HEIGHTS[integer_size - 1])
    } else {
        (font_size * 1.32).round().max(1.0)
    }
}

