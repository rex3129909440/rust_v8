fn kerning_100(family: &str, left: char, right: char) -> f64 {
    let table = if family.contains("times new roman") {
        TIMES_NEW_ROMAN_KERNING_100
    } else if family.contains("segoe ui") {
        SEGOE_UI_KERNING_100
    } else if family.contains("arial") {
        ARIAL_KERNING_100
    } else {
        return 0.0;
    };
    let Ok(left) = u8::try_from(left as u32) else {
        return 0.0;
    };
    let Ok(right) = u8::try_from(right as u32) else {
        return 0.0;
    };
    table
        .binary_search_by_key(&(left, right), |(left, right, _)| (*left, *right))
        .ok()
        .map(|index| table[index].2)
        .unwrap_or(0.0)
}
