pub(crate) fn ascii_advance_width(font: &str, text: &str, font_size: f64) -> Option<f64> {
    let lower = font.to_ascii_lowercase();
    let table = if lower.contains("times new roman") {
        &TIMES_NEW_ROMAN_ASCII_100
    } else if lower.contains("segoe ui") {
        &SEGOE_UI_ASCII_100
    } else if lower.contains("arial") {
        &ARIAL_ASCII_100
    } else {
        return None;
    };
    let mut width = 0.0;
    let mut previous = None;
    for character in text.chars() {
        if !((' '..='~').contains(&character)) {
            return None;
        }
        let mut advance = table[character as usize - 32];
        if let Some(left) = previous {
            advance += kerning_100(lower.as_str(), left, character);
        }
        // Chromium exposes each DirectWrite glyph advance after it has been
        // converted to Blink's 16.16 fixed-point text coordinate.  Scaling a
        // complete run and quantizing only the final value is observably
        // different for fractional CSS font sizes: at 13.33px, for example,
        // Arial `A large contentful text` is 128.93234252929688 in Edge, not
        // 128.9326025390625.  Apply the fixed-point floor per positioned glyph
        // (including its pair adjustment), which also preserves exact results
        // at integer sizes.
        let scaled = advance * font_size / 100.0;
        width += (scaled * 65_536.0).floor() / 65_536.0;
        previous = Some(character);
    }
    Some(width)
}

