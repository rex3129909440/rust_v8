pub(crate) fn dom_whitespace_kerning_100(font: &str, left: char, right: char) -> f64 {
    if left != ' ' && right != ' ' {
        return 0.0;
    }
    let lower = font.to_ascii_lowercase();
    if lower.contains("times new roman") {
        if right == ' ' {
            match left {
                'A' => -5.515625,
                'L' | 'P' => -3.71875,
                'T' | 'W' => -1.8125,
                'V' => -1.796875,
                'Y' => -3.703125,
                _ => 0.0,
            }
        } else {
            match right {
                'A' => -5.515625,
                'T' | 'V' | 'W' => -1.796875,
                'Y' => -3.703125,
                _ => 0.0,
            }
        }
    } else if lower.contains("arial") {
        if right == ' ' {
            match left {
                'A' => -5.515625,
                'L' => -3.71875,
                'P' | 'Y' => -1.796875,
                'T' => -1.8125,
                _ => 0.0,
            }
        } else {
            match right {
                // Blink's DOM inline shaping uses a -0.875px space/A
                // adjustment at 16px Arial (distinct from Canvas advance).
                'A' => -5.46875,
                'T' | 'Y' => -1.8125,
                _ => 0.0,
            }
        }
    } else {
        0.0
    }
}

