pub(crate) fn paint_overflow(
    font: &str,
    character: char,
    font_size: f64,
    implicit_default: bool,
    advance: f64,
) -> (f64, f64) {
    if !((' '..='~').contains(&character)) || font_size <= 0.0 {
        return (0.0, 0.0);
    }
    let index = character as usize - 32;
    let lower = font.to_ascii_lowercase();
    let (left, right_edge) = if implicit_default {
        (
            IMPLICIT_DEFAULT_PAINT_LEFT_100[index],
            IMPLICIT_DEFAULT_PAINT_RIGHT_EDGE_100[index],
        )
    } else if lower.contains("times new roman") {
        (
            TIMES_NEW_ROMAN_PAINT_LEFT_100[index],
            TIMES_NEW_ROMAN_PAINT_RIGHT_EDGE_100[index],
        )
    } else if lower.contains("segoe ui") {
        (
            SEGOE_UI_PAINT_LEFT_100[index],
            SEGOE_UI_PAINT_RIGHT_EDGE_100[index],
        )
    } else if lower.contains("arial") {
        (
            ARIAL_PAINT_LEFT_100[index],
            ARIAL_PAINT_RIGHT_EDGE_100[index],
        )
    } else {
        return (0.0, 0.0);
    };
    let scale = font_size / 100.0;
    let left_overflow = (f64::from(left) * scale).ceil().max(0.0);
    let right_overflow = ((f64::from(right_edge) * scale).ceil() - advance).max(0.0);
    (left_overflow, right_overflow)
}

pub(crate) fn ascii_text_ink_bounds(
    font: &str,
    text: &str,
    font_size: f64,
    advance: f64,
) -> Option<(f64, f64)> {
    let first = text.chars().next()?;
    let last = text.chars().next_back()?;
    if !text
        .chars()
        .all(|character| (' '..='~').contains(&character))
        || font_size <= 0.0
    {
        return None;
    }
    let lower = font.to_ascii_lowercase();
    let (left_table, right_table, family) = if lower.contains("times new roman") {
        (
            &TIMES_NEW_ROMAN_PAINT_LEFT_100,
            &TIMES_NEW_ROMAN_PAINT_RIGHT_EDGE_100,
            "times",
        )
    } else if lower.contains("segoe ui") {
        (
            &SEGOE_UI_PAINT_LEFT_100,
            &SEGOE_UI_PAINT_RIGHT_EDGE_100,
            "segoe",
        )
    } else if lower.contains("arial") {
        (&ARIAL_PAINT_LEFT_100, &ARIAL_PAINT_RIGHT_EDGE_100, "arial")
    } else {
        return None;
    };
    let first_index = first as usize - 32;
    let last_index = last as usize - 32;
    let scale = font_size / 100.0;
    let left = match (family, first) {
        ("arial", 'H') => -(font_size / 16.0).floor(),
        ("times", 'A' | 'H') if font_size < 32.0 => 1.0,
        ("times", 'A' | 'H') => 0.0,
        ("segoe", 'A') if font_size < 32.0 => 1.0,
        ("segoe", 'A') => 0.0,
        ("segoe", 'H') if font_size >= 16.0 => -(font_size / 12.0).floor(),
        _ => (f64::from(left_table[first_index]) * scale).ceil(),
    };
    let last_advance = ascii_advance_width(font, &last.to_string(), font_size)?;
    let mut last_ink_edge = (f64::from(right_table[last_index]) * scale).ceil();
    if family == "arial"
        && last == 'g'
        && font_size <= 16.0
        && (f64::from(right_table[last_index]) * scale).fract().abs() <= f64::EPSILON
    {
        last_ink_edge += 1.0;
    }
    if family == "times" && last == 't' && font_size <= 10.0 {
        last_ink_edge += 1.0;
    }
    if family == "times" && last == 'g' && font_size <= 10.0 {
        last_ink_edge += 1.0;
    }
    Some((left, advance - last_advance + last_ink_edge))
}
